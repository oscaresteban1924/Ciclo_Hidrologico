# Alternativa sin WebGL2: Chrome con las API 3D desactivadas → mapa 2D con el mismo cálculo.
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox', '--disable-3d-apis'])
    pg = b.new_page(viewport={'width': 1280, 'height': 800})
    logs = []
    pg.on('console', lambda m: logs.append(f'{m.type}: {m.text}') if m.type in ('error', 'warning') else None)
    pg.on('pageerror', lambda e: logs.append(f'pageerror: {e}'))
    pg.goto('http://127.0.0.1:5173/#recorrido')
    pg.wait_for_timeout(1000)
    pg.get_by_role('button', name='Medellín: laboratorio de lluvia').click()
    pg.wait_for_selector('.city-pick', timeout=30000)
    pg.wait_for_timeout(500)
    print('aviso sin WebGL2:', pg.locator('.city-valley2d').inner_text()[:140])
    pg.screenshot(path='/home/claude/shots/city/2d-valle.png')
    pg.locator('.city-pick button', has_text='Calle de prueba').click()
    pg.wait_for_selector('.city-simbar', timeout=30000)
    pg.evaluate("() => { const c = window.__cityDebug.controller; c.update({ shared: { rain: { ...c.shared.rain, intensityMmH: 100 } } }); c.start(); c.displayed().advanceTo(15*60); }")
    pg.wait_for_timeout(1500)
    pg.screenshot(path='/home/claude/shots/city/2d-sector.png')
    box = pg.locator('.city-canvas-host').bounding_box()
    pg.mouse.click(box['x'] + box['width'] * 0.58, box['y'] + box['height'] * 0.5)
    pg.wait_for_timeout(600)
    print('tarjeta 2D:', pg.locator('.city-card').inner_text()[:160].replace('\n', ' | ') if pg.locator('.city-card').count() else 'sin tarjeta')
    print('docente:', end=' ')
    pg.get_by_role('tab', name='Docente').click()
    pg.get_by_role('button', name='Resolución y rendimiento').click()
    print(pg.locator('text=Dibujo:').first.inner_text()[:160])
    print('\n'.join(logs[:10]) or 'consola limpia')
    b.close()
